-- Custom requests that aren't catalog products: crafts (reference photos) and printing (documents).
-- Private like orders: RLS on with no policies, only the server (secret key) reads/writes.

create table public.service_requests (
  id             uuid primary key, -- generated by the server before the upload, also the Storage folder
  kind           text not null check (kind in ('crafts', 'printing')),
  status         text not null default 'new' check (status in ('new', 'contacted', 'done', 'discarded')),
  customer_name  text not null check (length(trim(customer_name)) between 2 and 120),
  customer_phone text not null check (length(trim(customer_phone)) between 8 and 20),
  notes          text check (notes is null or length(notes) <= 1000),
  -- printing: { color_mode, copies, paper_size, sides }
  options        jsonb not null default '{}'::jsonb,
  -- [{ path, name, size, type }]
  files          jsonb not null default '[]'::jsonb,
  created_at     timestamptz not null default now()
);

create index service_requests_created_at_idx on public.service_requests (created_at desc);

alter table public.service_requests enable row level security;

-- Private bucket. Supabase itself rejects files over 20 MB or of other types.
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values (
  'service-requests',
  'service-requests',
  false,
  20 * 1024 * 1024,
  array[
    'image/jpeg', 'image/png', 'image/webp', 'image/heic', 'image/heif',
    'application/pdf',
    'application/msword',
    'application/vnd.openxmlformats-officedocument.wordprocessingml.document',
    'application/vnd.ms-excel',
    'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet',
    'application/vnd.ms-powerpoint',
    'application/vnd.openxmlformats-officedocument.presentationml.presentation'
  ]
)
on conflict (id) do update set
  public             = excluded.public,
  file_size_limit    = excluded.file_size_limit,
  allowed_mime_types = excluded.allowed_mime_types;
